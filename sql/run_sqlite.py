"""
run_sqlite.py

Runs Fantasy_Football_MYSQL.sql against SQLite and writes Result<N>.csv for
Query <N>, so the pipeline reproduces from a fresh clone without a MySQL
server. The MySQL-only bits are translated on the fly:

    USE ...;                 dropped
    INDEX ... inside CREATE  dropped
    START TRANSACTION        BEGIN
    STDDEV()                 registered as population std dev (same as MySQL)

AUDITED 2026-10-21: the committed Result CSVs had drifted from the SQL file
(Result4 and Result10 had columns no query produces, and Result15 stopped at
exactly 1,000 rows, MySQL Workbench's default export limit). Everything in
this folder is now regenerated by this script.

    python load_raw_tables.py --sqlite fantasy_football.db
    python run_sqlite.py --db fantasy_football.db
"""
import argparse
import math
import re
import sqlite3
from pathlib import Path

import pandas as pd

SQL_DIR = Path(__file__).resolve().parent
SQL_FILE = SQL_DIR / "Fantasy_Football_MYSQL.sql"


class PopStdDev:
    """MySQL STDDEV() = population standard deviation (STDDEV_POP)."""

    def __init__(self):
        self.values = []

    def step(self, value):
        if value is not None:
            self.values.append(float(value))

    def finalize(self):
        n = len(self.values)
        if n == 0:
            return None
        mean = sum(self.values) / n
        return math.sqrt(sum((v - mean) ** 2 for v in self.values) / n)


def mysql_to_sqlite(sql_text: str) -> list[str]:
    """Strip comments, translate MySQL-only syntax, and split into statements."""
    lines = [ln.split("--", 1)[0] for ln in sql_text.splitlines()]
    text = "\n".join(lines)
    text = re.sub(r"^\s*USE\s+\w+\s*;", "", text, flags=re.M | re.I)
    text = re.sub(r",\s*INDEX\s+\w+\s*\([^)]*\)", "", text, flags=re.I)
    text = re.sub(r"\bSTART\s+TRANSACTION\b", "BEGIN", text, flags=re.I)
    return [s.strip() for s in text.split(";") if s.strip()]


def run(db_path: Path, out_dir: Path) -> list[Path]:
    con = sqlite3.connect(db_path)
    con.create_aggregate("STDDEV", 1, PopStdDev)
    written = []
    query_no = 0
    for stmt in mysql_to_sqlite(SQL_FILE.read_text()):
        if re.match(r"^(SELECT|WITH)\b", stmt, flags=re.I):
            query_no += 1
            df = pd.read_sql(stmt, con)
            path = out_dir / f"Result{query_no}.csv"
            df.to_csv(path, index=False)
            written.append(path)
            print(f"  Query {query_no:>2} -> {path.name} ({len(df):,} rows)")
        else:
            con.execute(stmt)
    con.commit()
    con.close()
    return written


def main():
    parser = argparse.ArgumentParser(description="Run the MySQL analysis file on SQLite.")
    parser.add_argument("--db", default=str(SQL_DIR / "fantasy_football.db"))
    parser.add_argument("--out", default=str(SQL_DIR))
    args = parser.parse_args()
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = run(Path(args.db), out_dir)
    # Results from an older, longer query list would otherwise linger and look current
    for stale in sorted(out_dir.glob("Result*.csv")):
        if stale not in written:
            stale.unlink()
            print(f"  Removed stale {stale.name}")


if __name__ == "__main__":
    main()
